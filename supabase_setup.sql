-- ============================================================
-- ITコーディネータ活動管理システム Supabase用 テーブル構築SQL
-- ============================================================

-- 既存テーブルのクリーンアップ（必要に応じて）
DROP TABLE IF EXISTS activity_logs CASCADE;
DROP TABLE IF EXISTS project_members CASCADE;
DROP TABLE IF EXISTS projects CASCADE;
DROP TABLE IF EXISTS clients CASCADE;
DROP TABLE IF EXISTS experts CASCADE;

-- 1. 専門家マスタ (experts)
CREATE TABLE experts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    cert_number TEXT NOT NULL UNIQUE,
    organization TEXT,
    prefecture TEXT,
    specialties TEXT[],
    status TEXT DEFAULT 'active' NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 顧客マスタ (clients)
CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    industry TEXT,
    contact_person TEXT,
    tel TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. 支援案件テーブル (projects)
CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT REFERENCES clients(id) ON DELETE RESTRICT,
    name TEXT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    budget BIGINT,
    planned_hours NUMERIC(6, 2),
    leader_id BIGINT REFERENCES experts(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. 案件メンバー中間テーブル (project_members)
CREATE TABLE project_members (
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    expert_id BIGINT REFERENCES experts(id) ON DELETE CASCADE,
    PRIMARY KEY (project_id, expert_id)
);

-- 5. 日次支援日報ログ (activity_logs)
CREATE TABLE activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    expert_id BIGINT REFERENCES experts(id) ON DELETE RESTRICT,
    hours NUMERIC(4, 1) NOT NULL,
    title TEXT NOT NULL,
    content TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Row Level Security (RLS) を有効化し、匿名キー (anon) での全操作を許可するポリシーを設定
ALTER TABLE experts ENABLE ROW LEVEL SECURITY;
ALTER TABLE clients ENABLE ROW LEVEL SECURITY;
ALTER TABLE projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE project_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE activity_logs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public all access on experts" ON experts FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on clients" ON clients FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on projects" ON projects FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on project_members" ON project_members FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on activity_logs" ON activity_logs FOR ALL USING (true) WITH CHECK (true);

